// Rotation d'une tuile vers la droite
Tuiles* tourner_vers_droite(Tuiles* t){
    Tuiles* new = t;
    int a = t->a;
    int b = t->b;
    int c = t->c;
    int d = t->d;
    new->a = d;
    new->b = a;
    new->c = b;
    new->d = c;
    return new;
}

// Rotation d'une tuile vers la gauche
Tuiles* tourner_vers_gauche(Tuiles* t){
    Tuiles* new = t;
    int a = t->a;
    int b = t->b;
    int c = t->c;
    int d = t->d;
    new->a=b;
    new->b=c;
    new->c=d;
    new->d=a;
    return new;
}

